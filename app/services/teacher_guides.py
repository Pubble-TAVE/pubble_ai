"""선생 LLM(OpenAI)에게만 붙이는 task별 작성 기준과 예시.

- 서비스 프롬프트(prompts.py)는 선생, 자체 모델 모두 같다.
- 선생 LLM은 여기 기준과 예시를 system에 더 받아서 정답 품질을 높인다.
- 학습 데이터는 (서비스 프롬프트 → 선생 답안) 쌍으로 만든다. 기준과 예시는 학습 입력에 넣지 않는다.
  → 자체 모델은 짧은 프롬프트만 보고도 선생처럼 쓰는 법을 배운다 (증류).
"""

COMMON = """[근거(evidence) 규칙]
- 문장의 내용이 직접 나오는 메시지 ID만 1~3개. 분위기만 비슷한 메시지는 넣지 않는다.
- 여러 사람이 같은 말을 하면 대표 메시지 2~3개만.
- 근거로 쓸 메시지가 없으면 그 문장을 쓰지 않는다.

[문장 규칙]
- 40자 이내, 명사형으로 끝낸다 (예: "교통 편의 vs 가게 수", "신촌으로 결정").
- 인원수, 퍼센트 같은 숫자는 쓰지 않는다 (숫자는 화면에 따로 표시됨). 날짜, 금액처럼 대화에 나온 값은 써도 된다.
- 사람 이름보다 이유와 내용 중심으로 쓴다. 익명 메시지의 작성자를 짐작하는 표현은 절대 쓰지 않는다."""

BOARD_SUMMARY = """[board_summary 작성 기준]
- 쟁점(issues): 의견이 왜 갈리는지. "A: 이유 vs B: 이유" 꼴로 이유를 대비시킨다.
  갈리는 게 없으면 빈 목록.
- 합의(agreements): 선택지와 상관없이 다들 동의한 부분 (예: 조건, 날짜, 방식).
  아직 1위인 선택지는 합의가 아니다. 명시적으로 동의한 것만.
- 각각 최대 3개. 같은 얘기는 하나로 합친다. 사담은 무시한다.

[예시]
메시지:
[m1] 해원: 홍대는 가게가 많아서 좋아요
[m2] 정은: 신촌이 교통이 훨씬 나아요
[m3] 지현: 저도 신촌이요 지하철역이랑 가까워서
[m4] 민지: 근데 다들 금요일 저녁은 괜찮은 거죠?
[m5] 해원: 넵 금요일 좋아요
출력:
{"issues": [{"text": "홍대: 가게 많음 vs 신촌: 교통 편함", "evidence": ["m1", "m2", "m3"]}],
 "agreements": [{"text": "금요일 저녁 진행", "evidence": ["m4", "m5"]}]}"""

CONCLUSION = """[conclusion 작성 기준]
- decision: 명시적인 합의가 있거나, 투표 결과가 있고 그 뒤로 반대가 이어지지 않을 때만. "OO으로 결정" 꼴.
  의견이 계속 갈리거나 결정이 안 났으면 null (지어내지 않는다).
- todos: 담당자가 대화에 분명히 나온 일만.
  - owner_id는 팀원 목록의 ID. "제가 할게요" = 보낸 사람, "OO님이 해주세요" = OO.
  - task는 "무엇을 하는지" 짧게 (예: "신촌 대관 예약", "견적 받기").
  - due_text는 마감 원문 표현 그대로 (예: "담주까지", "21일까지"), 없으면 null. due는 기준 날짜로 계산한 날짜.
  - 이미 할당된 할 일과 같은 일이면 existing_todo_id에 그 ID (새 할 일로 쓰지 않는다).
  - 담당자가 없는 일은 todos가 아니라 open_issues로.
- open_issues: 아직 정하지 못한 것, 담당자 없는 일. 질문 꼴이 아니라 명사형 (예: "예산 미정").
- flow: 3~5줄, 시간 순서. "처음엔 ~ / ~가 나오며 ~ / 최종 ~" 흐름이 보이게. 줄마다 근거.
- 익명 메시지의 의견도 결론, 흐름에 반영하되 "익명 의견" 이상으로 작성자를 드러내지 않는다.
- 수정 요청이 있으면 요청한 부분만 고치고 나머지는 이전 초안을 유지한다.

[예시]
기준 날짜: 2026-11-18 (수) / 팀원: u1 해원, u2 정은, u3 지현 / 이미 할당된 할 일: 없음
메시지:
[m1] 해원: 홍대 어때요
[m2] 지현: 신촌이 교통이 나아요
[m3] 해원: 생각해보니 신촌이 낫겠네요
[m4] 정은: 저도 신촌 좋아요
[m5] 지현: 그럼 신촌으로 하고 예약은 제가 담주까지 할게요
[m6] 정은: 예산은 아직 모르겠네
출력:
{"decision": {"text": "신촌으로 결정", "evidence": ["m4", "m5"]},
 "todos": [{"task": "신촌 대관 예약", "owner_id": "u3", "due_text": "담주까지", "due": "2026-11-29", "evidence": ["m5"], "existing_todo_id": null}],
 "open_issues": [{"text": "예산 미정", "evidence": ["m6"]}],
 "flow": [{"text": "처음엔 홍대 제안", "evidence": ["m1"]},
          {"text": "교통 얘기가 나오며 신촌으로 기욺", "evidence": ["m2", "m3"]},
          {"text": "전원 신촌 동의, 예약 담당 정함", "evidence": ["m4", "m5"]}]}"""

OPTION_NORMALIZE = """[option_normalize 작성 기준]
- name: 선택지만 짧은 명사로 (10자 이내). "쪽", "어때요", "같은 데" 같은 말은 뺀다.
- 기존 선택지와 같은 것(줄임말, 다른 이름, 더 구체적으로 말한 것)이면 matched_option_id에 그 ID.
  예: 기존 "홍대"에 "홍대입구 쪽" → 같은 것. 기존 "홍대"에 "합정" → 새 선택지.
- 숫자 안건은 구간 이름을 기존 형식에 맞춘다 (예: 기존 "1만원"이면 "2만원").

[예시]
기존 선택지: o1 홍대, o2 신촌 / 메시지: "홍대입구 쪽 어때요?"
출력: {"name": "홍대", "matched_option_id": "o1"}
기존 선택지: o1 홍대, o2 신촌 / 메시지: "건대 쪽도 괜찮지 않아요?"
출력: {"name": "건대", "matched_option_id": null}"""

TODO_CATCH = """[todo_catch 작성 기준]
- 마지막 메시지에서 누가 무엇을 하기로 했는지만 뽑는다. 바로 앞 메시지는 맥락용.
- owner_id: "제가 할게요" = 보낸 사람, "OO님이 해주세요"(OO이 거절하지 않은 경우) = OO.
  "누가 해야 할 텐데"처럼 담당자가 없으면 null.
- task: "무엇을 하는지" 짧게 (예: "견적 받기"). 앞 메시지를 봐야 알 수 있으면 합쳐서 구체적으로.
- due_text: 마감 원문 표현 그대로, 없으면 null. due: 기준 날짜로 계산한 날짜 또는 null.
- evidence: 할 일 메시지 ID (앞 메시지가 내용을 정했으면 같이).

[예시]
기준 날짜: 2026-11-18 (수) / 팀원: u1 해원, u2 정은
[m6] 정은: 견적은 누가 받아요?
[m7] 해원: 그럼 제가 담주까지 받아올게요
출력: {"task": "견적 받기", "owner_id": "u1", "due_text": "담주까지", "due": "2026-11-29", "evidence": ["m6", "m7"]}"""

NEXT_AGENDA = """[next_agenda 작성 기준]
- 지금 안건이 끝난 뒤 따로 정해야 할 것만. 지금 안건 안에서 바로 정할 수 있는 건 빼고, 사담은 무시한다.
- title: 15자 이내 명사형 (예: "회비 금액", "뒤풀이 장소").
- reason: 왜 필요한지 한 줄 (예: "대관 장소는 정했지만 예산이 미정").
- 이미 있는 후보, 이미 있는 안건과 겹치면 쓰지 않는다. 쓸 게 없으면 빈 목록.

[예시]
미결 사항: 예산 미정 (근거: m6) / 다른 안건 메시지: [m9] 민지: 근데 뒤풀이는 어디서 해요?
출력: {"candidates": [{"title": "회비 금액", "reason": "장소는 정했지만 예산이 미정", "evidence": ["m6"]},
                      {"title": "뒤풀이 장소", "reason": "뒤풀이 장소 질문이 나옴", "evidence": ["m9"]}]}"""

GUIDES = {
    "board_summary": BOARD_SUMMARY,
    "conclusion": CONCLUSION,
    "option_normalize": OPTION_NORMALIZE,
    "todo_catch": TODO_CATCH,
    "next_agenda": NEXT_AGENDA,
}


def teacher_system(base_system: str, task: str) -> str:
    return f"{base_system}\n\n{COMMON}\n\n{GUIDES[task]}"
